"""Le migrazioni Alembic devono creare esattamente lo schema dei modelli, e tornare indietro."""

from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect

import segnalazioni.db
from segnalazioni.db import Database


def cfg_for(conn) -> Config:
    cfg = Config()
    cfg.set_main_option("script_location", str(Path(segnalazioni.db.__file__).parent / "migrations"))
    cfg.attributes["connection"] = conn
    return cfg


def test_schema_allineato_ai_modelli(database_url):
    db = Database(database_url)
    assert db.migrate() == "aggiornato"
    with db.engine.begin() as conn:
        try:
            command.check(cfg_for(conn))
        except AutogenerateDiffsDetected as e:  # modello cambiato senza nuova migrazione
            raise AssertionError(f"serve una nuova migrazione: {e}") from e
    assert {"prove", "alembic_version"} <= set(inspect(db.engine).get_table_names())
    assert db.migrate() == "aggiornato"  # la seconda volta non fa niente
    db.dispose()


def test_downgrade_e_upgrade(database_url):
    db = Database(database_url)
    db.migrate()
    with db.engine.begin() as conn:
        command.downgrade(cfg_for(conn), "base")
    # resta solo la tabella di PostGIS (l'estensione non si toglie)
    assert set(inspect(db.engine).get_table_names()) <= {"alembic_version", "spatial_ref_sys"}
    db.migrate()
    assert "prove" in inspect(db.engine).get_table_names()
    db.dispose()
